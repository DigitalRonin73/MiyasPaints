function getSavedLanguage() {
  try {
    return window.localStorage.getItem(languageStorageKey) || "en";
  } catch {
    return "en";
  }
}

function saveLanguage(language) {
  try {
    window.localStorage.setItem(languageStorageKey, language);
  } catch {
    // Some private browser contexts block storage. The toggle still works for this visit.
  }
}

function localizedValue(value, language = activeLanguage) {
  if (value && typeof value === "object" && !Array.isArray(value)) {
    return value[language] || value[fallbackLanguage] || "";
  }

  return value || "";
}

function seatsLabel(seatsLeft, language = activeLanguage) {
  if (seatsLeft && typeof seatsLeft === "object" && !Array.isArray(seatsLeft)) {
    return localizedValue(seatsLeft, language);
  }

  const dictionary = translations[language] || translations[fallbackLanguage];
  return dictionary.seatsLeft.replace("{count}", String(seatsLeft));
}

function renderEventCard(card, event) {
  const image = card.querySelector('[data-event-field="image"]');
  const dateCard = card.querySelector('[data-event-field="dateCard"]');
  const fields = {
    month: localizedValue(event.month),
    day: event.day,
    weekday: localizedValue(event.weekday),
    title: localizedValue(event.title),
    availabilityNote: localizedValue(event.availabilityNote),
    date: localizedValue(event.date),
    time: localizedValue(event.time),
    location: localizedValue(event.location),
    price: localizedValue(event.price)
  };

  if (image) {
    image.src = event.image;
    image.alt = localizedValue(event.imageAlt);
  }

  if (dateCard) {
    dateCard.dateTime = event.isoDate;
  }

  Object.entries(fields).forEach(([field, value]) => {
    card.querySelectorAll(`[data-event-field="${field}"]`).forEach((element) => {
      element.textContent = value;
    });
  });

  card.dataset.seatsLeft = seatsLabel(event.seatsLeft);
}

function renderEventCards() {
  document.querySelectorAll(".event-card[data-event-id]").forEach((card) => {
    const event = classEvents[card.dataset.eventId];
    if (event) {
      renderEventCard(card, event);
    }
  });
}

function applyLanguage(language) {
  activeLanguage = translations[language] ? language : fallbackLanguage;
  const dictionary = translations[activeLanguage] || translations[fallbackLanguage];

  document.documentElement.lang = activeLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (dictionary[key]) {
      element.placeholder = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (dictionary[key]) {
      element.alt = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (dictionary[key]) {
      element.setAttribute("aria-label", dictionary[key]);
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === activeLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  renderEventCards();
  if (selectedClassEventId && classEvents[selectedClassEventId]) {
    showSelectedClassSummary(classEvents[selectedClassEventId]);
  }
  saveLanguage(activeLanguage);
}

function showSelectedClassSummary(event) {
  if (!selectedClassSummary) {
    return;
  }

  const fields = {
    title: localizedValue(event.title),
    datetime: `${localizedValue(event.date)} ${localizedValue(event.time)}`,
    availability: seatsLabel(event.seatsLeft)
  };

  Object.entries(fields).forEach(([field, value]) => {
    selectedClassSummary.querySelectorAll(`[data-selected-class-field="${field}"]`).forEach((element) => {
      element.textContent = value;
    });
  });

  selectedClassSummary.hidden = false;
}

function setFormStatus(message, type = "info") {
  if (!formStatus) {
    return;
  }

  formStatus.textContent = message;
  formStatus.dataset.status = type;
}

function resetTurnstile() {
  if (window.turnstile && turnstileWidgetId !== null) {
    window.turnstile.reset(turnstileWidgetId);
  }
}

function getTurnstileToken() {
  if (window.turnstile && turnstileWidgetId !== null) {
    return window.turnstile.getResponse(turnstileWidgetId);
  }

  const tokenInput = reservationForm.querySelector('[name="cf-turnstile-response"]');
  return tokenInput ? tokenInput.value : "";
}

function waitForTurnstile() {
  return new Promise((resolve) => {
    if (window.turnstile) {
      resolve(window.turnstile);
      return;
    }

    const startedAt = Date.now();
    const interval = window.setInterval(() => {
      if (window.turnstile || Date.now() - startedAt > 8000) {
        window.clearInterval(interval);
        resolve(window.turnstile || null);
      }
    }, 100);
  });
}

async function setupTurnstile() {
  if (!turnstileContainer) {
    return;
  }

  try {
    const [turnstile, response] = await Promise.all([
      waitForTurnstile(),
      fetch("/api/config", { cache: "no-store" })
    ]);
    const config = response.ok ? await response.json() : {};

    if (!turnstile || !config.turnstileSiteKey) {
      return;
    }

    turnstileWidgetId = turnstile.render(turnstileContainer, {
      sitekey: config.turnstileSiteKey
    });
  } catch {
    setFormStatus(translations[activeLanguage].formVerificationError, "error");
  }
}

