function getSavedLanguage() {
  try {
    return window.localStorage.getItem(languageStorageKey) || "en";
  } catch {
    return "en";
  }
}

function saveLanguage(language) {
  try {
    window.localStorage.setItem(languageStorageKey, language);
  } catch {
    // Some private browser contexts block storage. The toggle still works for this visit.
  }
}

function localizedValue(value, language = activeLanguage) {
  if (value && typeof value === "object" && !Array.isArray(value)) {
    return value[language] || value.en || "";
  }

  return value || "";
}

function seatsLabel(seatsLeft, language = activeLanguage) {
  const dictionary = translations[language] || translations.en;
  return dictionary.seatsLeft.replace("{count}", String(seatsLeft));
}

function renderEventCard(card, event) {
  const image = card.querySelector('[data-event-field="image"]');
  const dateCard = card.querySelector('[data-event-field="dateCard"]');
  const fields = {
    month: event.month,
    day: event.day,
    weekday: event.weekday,
    seats: seatsLabel(event.seatsLeft),
    title: localizedValue(event.title),
    date: event.date,
    time: event.time,
    location: event.location,
    price: event.price,
    description: localizedValue(event.description)
  };

  if (image) {
    image.src = event.image;
    image.alt = localizedValue(event.imageAlt);
  }

  if (dateCard) {
    dateCard.dateTime = event.isoDate;
  }

  Object.entries(fields).forEach(([field, value]) => {
    card.querySelectorAll(`[data-event-field="${field}"]`).forEach((element) => {
      element.textContent = value;
    });
  });

  card.dataset.seatsLeft = String(event.seatsLeft);
}

function renderEventCards() {
  document.querySelectorAll(".event-card[data-event-id]").forEach((card) => {
    const event = classEvents[card.dataset.eventId];
    if (event) {
      renderEventCard(card, event);
    }
  });
}

function applyLanguage(language) {
  const dictionary = translations[language] || translations.en;
  activeLanguage = translations[language] ? language : "en";

  document.documentElement.lang = activeLanguage === "ja" ? "ja" : "en";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (dictionary[key]) {
      element.placeholder = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (dictionary[key]) {
      element.alt = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (dictionary[key]) {
      element.setAttribute("aria-label", dictionary[key]);
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === activeLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  renderEventCards();
  saveLanguage(activeLanguage);
}

function closeMobileMenu() {
  document.body.classList.remove("nav-open");
  navMenu.classList.remove("is-open");
  navActions.classList.remove("is-open");
  navToggle.setAttribute("aria-expanded", "false");
}

navToggle.addEventListener("click", () => {
  const isOpen = navToggle.getAttribute("aria-expanded") === "true";
  document.body.classList.toggle("nav-open", !isOpen);
  navMenu.classList.toggle("is-open", !isOpen);
  navActions.classList.toggle("is-open", !isOpen);
  navToggle.setAttribute("aria-expanded", String(!isOpen));
});

document.querySelectorAll(".nav-menu a, .nav-actions a").forEach((link) => {
  link.addEventListener("click", closeMobileMenu);
});

bookClassButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const dictionary = translations[activeLanguage] || translations.en;
    const event = classEvents[button.dataset.eventId];

    if (!event) {
      return;
    }

    const classTitle = localizedValue(event.title);
    const classDate = event.date;
    const classTime = event.time;

    reservationForm.elements["selected-class"].value = classTitle;
    reservationForm.elements["class-date"].value = classDate;
    reservationForm.elements.message.value = dictionary.bookingMessage
      .replace("{classTitle}", classTitle)
      .replace("{classDate}", classDate)
      .replace("{classTime}", classTime);

    formStatus.textContent = "";
    setTimeout(() => {
      reservationForm.elements.name.focus({ preventScroll: true });
    }, 350);
  });
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.lang);
  });
});

reservationForm.addEventListener("submit", (event) => {
  event.preventDefault();
  formStatus.textContent = translations[activeLanguage].formSuccess;
  reservationForm.reset();
});

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.14 }
);

document.querySelectorAll(".reveal").forEach((element) => {
  revealObserver.observe(element);
});

applyLanguage(savedLanguage);
